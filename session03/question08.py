#موجودی حساب و مبلغ برداشت  را دریافت کن
#اگرموجودی کافی بود به نسبت برداشت و برداشت کن
#اگر مبلغ بیشتر از موجودی بود خطا
#اگر مبلغ برداشت صفر یا منفی صفر بود خطا بزن
aco = int(input("موجودی حساب خود را وارد کنید: "))
num = int(input("مبلغی که میخواهید برداشت کنید وارد کنید:"))
if num <= 0:
    print("عدد وارد شده صحیح نیست")
elif num < aco:
    z = num - aco
    print(f"برداشت از حساب * مانده شما  : {z}")
else:
    print("موجودی کافی نمیباشد")